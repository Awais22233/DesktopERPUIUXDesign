import { launch, pickParty } from "./lib.mjs"

const { page, step, shot, nav, finish } = await launch("cosmetics", "Glow Cosmetics")
// The application keeps business dates in Pakistan time (UTC+5), so the test must too, or it is off by a day every evening.
const inTen = new Date(Date.now() + 5 * 3_600_000 + 10 * 86_400_000).toISOString().slice(0, 10)

await step("first-run owner setup", async () => {
  await page.waitForSelector("text=Create the owner account")
  await page.locator("input[name=name]").fill("Sara")
  await page.locator("input[name=username]").fill("sara")
  await page.locator("input[name=password]").fill("secret1")
  await page.locator("input[name=again]").fill("secret1")
  await page.getByRole("button", { name: "Create account" }).click()
  await page.waitForSelector("text=Business overview")
})
await step("cosmetics profile hides cloth-only features and wording", async () => {
  const side = await page.locator("aside").innerText()
  if (!/Recovery/.test(side)) throw new Error("Recovery is missing (cosmetics wholesalers also sell on credit)")
  if (/City/.test(side)) throw new Error("a cloth-only city screen is visible")
  const t = await page.locator("body").innerText()
  if (/Than/.test(t)) throw new Error("the word Than is visible")
})
await step("add a product with size and barcode", async () => {
  await nav("Inventory")
  await page.getByRole("button", { name: "Add product" }).first().click()
  await page.locator("input[name=company]").fill("Lifebuoy")
  await page.locator("input[name=article]").fill("Shampoo Anti-Dandruff")
  await page.locator("input[name=size]").fill("180 ml")
  await page.locator("input[name=barcode]").fill("8901234567890")
  await page.locator("input[name=cost]").fill("200")
  await page.locator("input[name=rate]").fill("300")
  // A real (tiny) PNG: the app must shrink it to JPEG thumbnails and store it.
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==", "base64")
  await page.locator("input[data-testid=photo-input]").setInputFiles({ name: "shampoo.png", mimeType: "image/png", buffer: png })
  await page.waitForSelector(".photo-box img")
  await page.getByRole("button", { name: "Add product" }).last().click()
  await page.waitForSelector("text=Shampoo Anti-Dandruff")
  await page.waitForSelector("img.row-photo")
})
await step("the product photo shows in the POS grid (cosmetics default) and loads from disk", async () => {
  await nav("POS / Sales")
  await page.waitForSelector(".product-grid .product-card")
  const ok = await page.locator(".product-card img.card-photo").first().evaluate((i) => i.complete && i.naturalWidth > 0)
  if (!ok) throw new Error("the stored photo did not load in the POS grid")
  await page.getByTitle("List").click()
  await page.waitForSelector(".product-picker:not([hidden]) .product-option")
  await page.getByTitle("Photo grid").click()
})
await step("removing the photo goes back to the letter placeholder", async () => {
  await nav("Inventory")
  await page.getByText("Shampoo Anti-Dandruff").first().click()
  await page.getByRole("button", { name: /Edit/ }).first().click()
  await page.waitForSelector(".photo-box img")
  await page.getByRole("button", { name: "Remove" }).click()
  await page.getByRole("button", { name: /Save|Update/ }).last().click()
  await page.waitForFunction(() => !document.querySelector("img.row-photo"))
})
await step("add a supplier and receive stock with batch and expiry", async () => {
  await nav("Suppliers")
  await page.getByRole("button", { name: /Add supplier/ }).first().click()
  await page.locator("input[name=name]").fill("Beauty Wholesale")
  await page.getByRole("button", { name: /Add party|Add supplier/ }).last().click()
  await page.waitForSelector("text=Beauty Wholesale")
  await nav("Purchases")
  await page.getByRole("button", { name: /New purchase/ }).first().click()
  await page.waitForSelector("text=Purchase details")
  await pickParty(page, "Beauty Wholesale")
  await page.getByText("Shampoo Anti-Dandruff").first().click()
  await page.getByLabel(/Quantity of Shampoo/).fill("24")
  await page.getByLabel(/Batch of Shampoo/).fill("B-101")
  await page.getByLabel(/Expiry of Shampoo/).fill(inTen)
  await page.getByRole("button", { name: /Save purchase/ }).click()
  await page.waitForSelector("text=/Purchase PUR-00001 saved/")
})
await step("scanning a barcode adds the item; walk-in customer pays in full", async () => {
  await nav("POS / Sales")
  const chosen = await page.locator(".party-picker input[role=combobox]").first().inputValue()
  if (chosen !== "Walk-in customer") throw new Error("a counter shop should start with the walk-in customer chosen, got: " + chosen)
  const search = page.getByPlaceholder(/Scan a barcode/)
  await search.fill("8901234567890")
  await search.press("Enter")
  await page.getByLabel(/Quantity of Shampoo/).fill("3")
  await page.getByRole("button", { name: /Save sale/ }).click()
  await page.waitForSelector("text=/Sale INV-00001 saved/")
})
await step("the dashboard warns about the batch that expires soon", async () => {
  await nav("Dashboard")
  await page.waitForSelector("text=Expiry alerts")
  await page.waitForSelector("text=B-101")
  await page.waitForSelector("text=/10 days left/")
  await shot("expiry-alert")
})
await step("the near-expiry report lists the batch", async () => {
  await nav("Reports")
  await page.locator(".report-categories button", { hasText: "Inventory" }).click()
  await page.getByText("Near Expiry", { exact: true }).first().click()
  await page.getByRole("button", { name: "Generate report" }).click()
  await page.waitForSelector("text=B-101")
})
await finish()
