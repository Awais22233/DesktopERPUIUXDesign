await step("bill with line discount and invoice discount, and a purchase bill number can be changed", async () => {
  await nav("POS / Sales")
  await page.locator("select", { hasText: "Select party" }).selectOption({ label: "Gul Ahmed Store" })
  await page.locator(".group-card, .group-option", { hasText: "Cotton Grey" }).getByRole("button", { name: /^28 m ×/ }).click()
  await page.getByLabel(/Rate for Cotton Grey/).fill("200")
  await page.getByLabel(/Discount for Cotton Grey/).fill("100")
  await page.locator("input[type=number]").last().fill("0").catch(() => {})
  await page.getByRole("button", { name: /Save & print/ }).click()
  await page.waitForSelector("text=SALES INVOICE")
  const bill = await page.locator(".invoice-paper").innerText()
  if (!/Disc\./.test(bill) || !/Rs\. 100/.test(bill) || !/5,500/.test(bill)) throw new Error("discount missing on the bill: " + bill.slice(0, 600))
  await page.keyboard.press("Escape")
  const pd = await call("docs:list", { kind: "purchase", pageSize: 1 })
  const r = await call("purchase:renumber", { id: pd.data.rows[0].id, purchaseNo: "P-501" })
  if (!r.ok) throw new Error(JSON.stringify(r))
  const again = await call("docs:list", { kind: "purchase", no: "P-501", pageSize: 1 })
  if (!again.data.rows.length) throw new Error("purchase not found under the new number")
})

await finish()
