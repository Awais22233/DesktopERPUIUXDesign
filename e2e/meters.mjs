import { launch } from "./lib.mjs"

const { page, step, shot, nav, finish } = await launch("cloth", "Gul Cloth House", { profitHidden: true })
const call = (ch, req) => page.evaluate(([c, r]) => window.api.invoke(c, r), [ch, req])
let supplier

await step("owner setup, a product without any length, a supplier and a customer", async () => {
  await page.waitForSelector("text=Create the owner account")
  await page.locator("input[name=name]").fill("Owner")
  await page.locator("input[name=username]").fill("owner")
  await page.locator("input[name=password]").fill("secret1")
  await page.locator("input[name=again]").fill("secret1")
  await page.getByRole("button", { name: "Create account" }).click()
  await page.waitForSelector("text=Business overview")
  supplier = (await call("party:save", { kind: "supplier", name: "ABC Textile", city: "Karachi" })).data.id
  await call("party:save", { kind: "customer", name: "Gul Ahmed Store", city: "Ghotki" })
  const p = await call("product:save", { company: "Gul", article: "Lawn", color: "Blue", cost: 0, rate: 0, minStock: 0 })
  if (!p.ok) throw new Error(JSON.stringify(p))
  await page.reload()
  await page.waitForSelector("text=Business overview")
})
await step("purchase by the meter in the screen: first length, then a new length on the same product", async () => {
  await nav("Purchases")
  await page.getByRole("button", { name: /New purchase/ }).first().click()
  await page.waitForSelector("text=Purchase details")
  await page.locator("select", { hasText: "Select supplier" }).selectOption({ label: "ABC Textile" })
  await page.getByRole("button", { name: "+ new length" }).click()
  await page.getByLabel(/Length of Lawn Blue/).fill("20")
  await page.getByLabel(/Quantity of Lawn Blue/).fill("5")
  await page.getByLabel(/Rate for Lawn Blue/).fill("100")
  await page.getByRole("button", { name: "+ new length" }).click()
  await page.getByLabel(/Length of Lawn Blue/).nth(1).fill("22.5")
  await page.getByLabel(/Quantity of Lawn Blue/).nth(1).fill("4")
  await page.getByLabel(/Rate for Lawn Blue/).nth(1).fill("110")
  await page.getByRole("button", { name: /Save purchase/ }).click()
  await page.waitForSelector("text=/Purchase PUR-\\d+ saved/")
  // 5 x 20 m x 100 = 10,000 ; 4 x 22.5 m x 110 = 9,900
  const d = await call("docs:list", { kind: "purchase", pageSize: 1 })
  if (d.data.rows[0].total !== 19900) throw new Error("purchase total " + d.data.rows[0].total)
})
await step("inventory shows ONE product with a line per length and the meters", async () => {
  await nav("Inventory")
  await page.waitForSelector("text=Lawn Blue")
  const t = await page.locator("body").innerText()
  if ((t.match(/Lawn Blue/g) ?? []).length !== 1) throw new Error("the product is listed more than once")
  if (!/20 m × 5/.test(t) || !/22\.5 m × 4/.test(t)) throw new Error("lengths not shown")
  if (!/= 190 m/.test(t)) throw new Error("meters not shown: " + t.slice(0, 400))
  await shot("inventory-lengths")
})
await step("sale: 3 thans of 20 m and 2 of 22.5 m, rate per meter; bill shows the meters", async () => {
  await nav("POS / Sales")
  await page.locator("select", { hasText: "Select party" }).selectOption({ label: "Gul Ahmed Store" })
  await shot("pos-length-chips")
  await page.getByRole("button", { name: "20 m × 5" }).click()
  await page.getByRole("button", { name: "22.5 m × 4" }).click()
  await page.getByLabel(/Quantity of Lawn Blue/).nth(0).fill("3")
  await page.getByLabel(/Quantity of Lawn Blue/).nth(1).fill("2")
  await page.getByLabel(/Rate for Lawn Blue/).nth(0).fill("150")
  await page.getByLabel(/Rate for Lawn Blue/).nth(1).fill("160")
  // 3 x 20 x 150 = 9,000 ; 2 x 22.5 x 160 = 7,200
  await page.waitForSelector("text=/16,200/")
  await shot("pos-cart-meters")
  await page.getByRole("button", { name: /Save & print/ }).click()
  await page.waitForSelector("text=SALES INVOICE")
  const bill = await page.locator(".invoice-paper").innerText()
  // two different rates -> two rows, each with its breakdown and total meters
  if (!/\(3 × 20\)/.test(bill) || !/\(2 × 22\.5\)/.test(bill) || !/Total meters/.test(bill) || !/\b60\b/.test(bill) || !/\b45\b/.test(bill)) throw new Error("bill lacks the meters: " + bill.slice(0, 600))
  await shot("bill-meters")
  // changing the bill number must not close the bill
  await page.getByRole("button", { name: "Change bill number" }).click()
  await page.getByLabel("New bill number").fill("B-77")
  await page.getByRole("button", { name: "Save bill number" }).click()
  await page.waitForSelector(".invoice-no >> text=B-77")
  if (!(await page.locator(".invoice-paper").isVisible())) throw new Error("the bill closed")
})
await step("saved bill (from the books) has the lengths and the rate per meter", async () => {
  const d = await call("docs:list", { kind: "sale", pageSize: 1 })
  const lines = d.data.rows[0].lines.map((l) => [l.qty, l.length, l.rateM])
  if (JSON.stringify(lines) !== JSON.stringify([[3, 20, 150], [2, 22.5, 160]])) throw new Error(JSON.stringify(lines))
  if (d.data.rows[0].total !== 16200) throw new Error("total " + d.data.rows[0].total)
})
