import { launch } from "./lib.mjs"

const { page, step, shot, nav, finish } = await launch("cloth", "Search House")
const call = (ch, req) => page.evaluate(([c, r]) => window.api.invoke(c, r), [ch, req])
const must = (c, m) => { if (!c) throw new Error(m) }

await step("120 parties exist", async () => {
  await page.waitForSelector("text=Create the owner account")
  await page.locator("input[name=name]").fill("Owner")
  await page.locator("input[name=username]").fill("owner")
  await page.locator("input[name=password]").fill("secret1")
  await page.locator("input[name=again]").fill("secret1")
  await page.getByRole("button", { name: "Create account" }).click()
  await page.waitForSelector("text=Business overview")
  for (let i = 1; i <= 120; i++) await call("party:save", { kind: "customer", name: `Customer ${String(i).padStart(3, "0")}`, city: i % 2 ? "Ghotki" : "Sukkur", phone: `0300${1000000 + i}` })
  await call("party:save", { kind: "customer", name: "Ali Traders", city: "Multan" })
  await page.reload()
  await page.waitForSelector("text=Business overview")
})
await step("type to find a party in the sale screen, keyboard and mouse", async () => {
  await nav("POS / Sales")
  const box = page.locator(".party-picker input[role=combobox]").first()
  await box.click()
  must((await page.locator(".party-picker li[role=option]").count()) >= 80, "long list should be capped, not all rendered at once")
  await box.fill("ali")
  const n = await page.locator(".party-picker li[role=option]").allTextContents(); must(n.length === 1, "typing ali: " + JSON.stringify(n.slice(0, 5)))
  await page.keyboard.press("Enter")
  must((await box.inputValue()) === "Ali Traders", "Enter should choose the match")
  await box.click()
  await box.fill("0300100")
  await page.keyboard.press("ArrowDown")
  await page.keyboard.press("Enter")
  must((await box.inputValue()).startsWith("Customer 0"), "phone search + arrow keys")
  await box.click()
  await box.fill("sukkur 11")
  must((await page.locator(".party-picker li[role=option]").count()) >= 1, "city + number search")
  await page.keyboard.press("Escape")
  must((await page.locator(".party-picker li[role=option]").count()) === 0, "Escape closes the list")
  await shot("party-search")
})
await step("the same chooser in Receive payment", async () => {
  await nav("Recovery")
  await page.getByRole("button", { name: /Receive payment/ }).first().click()
  const box = page.locator(".party-picker input[role=combobox]").first()
  await box.click()
  await box.fill("Customer 077")
  await page.getByRole("option", { name: "Customer 077" }).click()
  must((await box.inputValue()) === "Customer 077", "chosen in the payment form")
})
await finish()
