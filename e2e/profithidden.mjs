import { launch } from "./lib.mjs"

const { page, step, shot, nav, finish } = await launch("cloth", "Quiet Cloth House", { profitHidden: true })
const call = (ch, req) => page.evaluate(([c, r]) => window.api.invoke(c, r), [ch, req])

await step("owner setup and a little business data", async () => {
  await page.waitForSelector("text=Create the owner account")
  await page.locator("input[name=name]").fill("Owner")
  await page.locator("input[name=username]").fill("owner")
  await page.locator("input[name=password]").fill("secret1")
  await page.locator("input[name=again]").fill("secret1")
  await page.getByRole("button", { name: "Create account" }).click()
  await page.waitForSelector("text=Business overview")
  const sup = await call("party:save", { kind: "supplier", name: "ABC Textile", city: "Karachi" })
  await call("party:save", { kind: "customer", name: "Gul Ahmed Store", city: "Ghotki" })
  const prod = await call("product:save", { company: "Gul", article: "Lawn", color: "Blue", size: "40 meter", cost: 0, rate: 0, minStock: 0 })
  if (!prod.ok) throw new Error("product not saved: " + JSON.stringify(prod))
  const p = await call("purchase:create", { supplierId: sup.data.id, lines: [{ productId: prod.data.id, qty: 20, rate: 1000 }], payments: [] })
  if (!p.ok) throw new Error("purchase not saved: " + JSON.stringify(p))
  await page.reload()
  await page.waitForSelector("text=Business overview")
})
await step("dashboard shows no profit and no stock value", async () => {
  await nav("Dashboard")
  await page.waitForSelector("text=Business overview")
  const t = await page.locator("body").innerText()
  if (/profit|margin|stock value/i.test(t)) throw new Error("profit or stock value is visible on the dashboard: " + t.match(/.{0,40}(profit|margin|stock value).{0,40}/i)?.[0])
  await shot("dashboard-no-profit")
})
await step("reports: no profit report is listed, the featured card is gone", async () => {
  await nav("Reports")
  await page.waitForSelector("text=Daily Sales")
  const t = await page.locator("body").innerText()
  if (/Profit & Loss|Profitability|Stock Valuation|Daily Profit/i.test(t)) throw new Error("a profit report is listed")
  const r = await call("report:run", { name: "Profit & Loss", from: "2026-01-01", to: "2026-12-31" })
  if (r.ok) throw new Error("the engine still runs Profit & Loss")
})
await step("inventory shows no cost or stock value; product form has no purchase price", async () => {
  await nav("Inventory")
  await page.waitForSelector("text=Lawn")
  const t = await page.locator("body").innerText()
  if (/Avg\. cost|Stock value/i.test(t)) throw new Error("cost columns are visible")
  await page.getByRole("button", { name: "Add product" }).click()
  await page.waitForSelector("text=Sale price")
  if (await page.locator("input[name=cost][type=number]").count()) throw new Error("the purchase price box is visible")
  const saleReq = await page.locator("input[name=rate]").getAttribute("required")
  if (saleReq !== null) throw new Error("sale price must be optional")
  await page.keyboard.press("Escape")
})
await step("POS: rate must be typed; a typed bill number is used; a repeat is refused", async () => {
  await nav("POS / Sales")
  await page.locator("select", { hasText: "Select party" }).selectOption({ label: "Gul Ahmed Store" })
  await page.getByText("Lawn Blue").first().click()
  await page.getByLabel(/Quantity of Lawn Blue/).fill("3")
  await page.getByRole("button", { name: /Save sale/ }).click()
  await page.waitForSelector("text=/Enter the rate/")
  await page.getByLabel(/Rate for Lawn Blue/).fill("1500")
  await page.getByLabel("Bill number").fill("A-117")
  await page.getByRole("button", { name: /Save sale/ }).click()
  await page.waitForSelector("text=/Sale A-117 saved/")
  await page.getByRole("button", { name: /Close|Done/ }).first().click().catch(() => {})
  // same number again
  await nav("POS / Sales")
  await page.locator("select", { hasText: "Select party" }).selectOption({ label: "Gul Ahmed Store" })
  await page.getByText("Lawn Blue").first().click()
  await page.getByLabel(/Rate for Lawn Blue/).fill("1500")
  await page.getByLabel("Bill number").fill("a-117")
  await page.getByRole("button", { name: /Save sale/ }).click()
  await page.waitForSelector("text=/already used/")
})
await step("the next suggestion follows the last number; the customer's last rate is prefilled", async () => {
  await page.getByLabel("Bill number").fill("")
  await page.reload()
  await page.waitForSelector("text=Business overview", { timeout: 15000 }).catch(() => {})
  await nav("POS / Sales")
  const v = await page.getByLabel("Bill number").inputValue()
  if (v !== "A-118") throw new Error("expected suggestion A-118, got " + v)
  await page.locator("select", { hasText: "Select party" }).selectOption({ label: "Gul Ahmed Store" })
  await page.getByText("Lawn Blue").first().click()
  await page.waitForFunction(() => document.querySelector('input[aria-label^="Rate for Lawn"]')?.value === "1500")
})
await step("a saved bill number can be changed", async () => {
  const r = await call("sale:renumber", { id: "A-117", invoiceNo: "9001" })
  if (!r.ok) throw new Error(JSON.stringify(r))
  const d = await call("docs:list", { kind: "sale", no: "9001", pageSize: 1 })
  if (!d.ok || d.data.rows[0]?.id !== "9001") throw new Error("renumbered bill not found")
  const bad = await call("sale:renumber", { id: "9001", invoiceNo: "9001" })
  if (!bad.ok) throw new Error("renumbering to its own number should be a no-op")
})

await finish()
