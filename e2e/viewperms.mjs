import { launch } from "./lib.mjs"

const { page, step, shot, nav, finish } = await launch("cosmetics", "Locked House")
const call = (ch, req) => page.evaluate(([c, r]) => window.api.invoke(c, r), [ch, req])
const must = (c, m) => { if (!c) throw new Error(m) }
const sidebar = () => page.locator("aside").innerText()

await step("setup the owner and a Sales User", async () => {
  await page.waitForSelector("text=Create the owner account")
  await page.locator("input[name=name]").fill("Owner")
  await page.locator("input[name=username]").fill("owner")
  await page.locator("input[name=password]").fill("secret1")
  await page.locator("input[name=again]").fill("secret1")
  await page.getByRole("button", { name: "Create account" }).click()
  await page.waitForSelector("text=Business overview")
  must((await call("user:create", { name: "Sami Sales", username: "sami", password: "sami123", role: "Sales User" })).ok, "user")
})
await step("owner sees Expenses and Cash & Bank; Settings is a quiet link that asks for the password", async () => {
  const t = await sidebar()
  must(t.includes("Expenses") && t.includes("Cash & Bank") && t.includes("Settings"), "owner menu: " + t)
  await page.locator("aside").getByText("Settings", { exact: true }).click()
  await page.waitForSelector("text=Settings are locked")
  await page.locator("input[name=password]").fill("wrong-one")
  await page.getByRole("dialog").getByRole("button", { name: "Open settings" }).click()
  await page.waitForSelector("text=not correct")
  must(await page.locator("text=Settings are locked").count() === 1, "must stay locked after a wrong password")
  await shot("settings-locked")
  await page.locator("input[name=password]").fill("secret1")
  await page.getByRole("dialog").getByRole("button", { name: "Open settings" }).click()
  await page.waitForSelector("text=Salesmen & recovery")
})
await step("leaving Settings locks it again", async () => {
  await nav("Dashboard")
  await page.locator("aside").getByText("Settings", { exact: true }).click()
  await page.waitForSelector("text=Settings are locked")
  await page.getByRole("button", { name: "Cancel" }).click()
})
await step("a Sales User has no Expenses, Cash & Bank or Settings, and receives no such data", async () => {
  await page.getByTitle("Lock workspace").click()
  await page.getByRole("button", { name: /Sign out|Lock|Confirm/ }).last().click()
  await page.waitForSelector("text=Sign in")
  await page.locator("input[name=username]").fill("sami")
  await page.locator("input[name=password]").fill("sami123")
  await page.getByRole("button", { name: "Sign in" }).click()
  await page.waitForSelector("text=Business overview")
  const t = await sidebar()
  for (const gone of ["Expenses", "Cash & Bank", "Settings"]) must(!t.includes(gone), gone + " still in the menu: " + t)
  const body = await page.locator("main, body").first().innerText()
  must(!body.includes("Today's expenses") && !body.includes("Expenses paid") && !body.includes("View cash & bank"), "dashboard still shows expense/cash links")
  const snap = (await call("snapshot:get")).data
  must(snap.expenses.length === 0 && snap.entries.length === 0, "history was sent")
  await shot("sales-user-menu")
})
await finish()
