#!/usr/bin/env node
// Vendor-side license tool. NEVER ship this folder's private key. Commands:
//   node tools/license.mjs init
//   node tools/license.mjs issue --client "Raza Textiles" --profile cloth --machine ABCDE-... [--expires 2027-12-31]
//   node tools/license.mjs inspect <key>
import { createHash, createPrivateKey, createPublicKey, generateKeyPairSync, randomBytes, sign, verify } from "node:crypto"
import { appendFileSync, chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const dir = process.env.ERP_LICENSE_DIR || join(homedir(), ".erp-license")
const privatePath = join(dir, "private.pem")
const pubFile = process.env.ERP_PUBLIC_KEY_FILE || resolve(here, "../src/main/license/publicKey.ts")
const b64u = (b) => Buffer.from(b).toString("base64url")

const args = process.argv.slice(2)
const cmd = args.shift()
const flag = (name) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 ? args[i + 1] : undefined
}
const die = (m) => {
  console.error("Error: " + m)
  process.exit(1)
}

function readPublicFromSource() {
  const m = readFileSync(pubFile, "utf8").match(/`(-----BEGIN PUBLIC KEY-----[\s\S]*?-----END PUBLIC KEY-----)\n?`/)
  if (!m) die(`No public key found in ${pubFile}. Run: node tools/license.mjs init`)
  return m[1]
}

if (cmd === "init") {
  if (existsSync(privatePath) && !args.includes("--force")) die(`A private key already exists at ${privatePath}. Re-initialising would invalidate every issued license. Use --force only if you are sure.`)
  const { publicKey, privateKey } = generateKeyPairSync("ed25519")
  mkdirSync(dir, { recursive: true })
  writeFileSync(privatePath, privateKey.export({ type: "pkcs8", format: "pem" }))
  try {
    chmodSync(privatePath, 0o600)
  } catch {}
  const pem = publicKey.export({ type: "spki", format: "pem" }).toString().trim()
  writeFileSync(pubFile, `// Generated by \`node tools/license.mjs init\`. Public key only; safe to commit.\nexport const PUBLIC_KEY_PEM = \`${pem}\n\`\n`)
  console.log(`Private key : ${privatePath}   <-- KEEP SECRET. Back it up offline. Never commit it.`)
  console.log(`Public key  : written to ${pubFile}`)
  console.log("Rebuild the application so installers contain this public key.")
} else if (cmd === "issue") {
  const client = flag("client")
  const profile = flag("profile")
  const machine = flag("machine")
  const expires = flag("expires")
  if (!client || !profile || !machine) die('Usage: issue --client "Name" --profile cloth|cosmetics --machine XXXXX-XXXXX-XXXXX-XXXXX [--expires YYYY-MM-DD]')
  if (!["cloth", "cosmetics"].includes(profile)) die("profile must be cloth or cosmetics")
  if (!/^[0-9A-F]{5}(-[0-9A-F]{5}){3}$/.test(machine.toUpperCase())) die("machine id must look like ABCDE-12345-ABCDE-12345")
  if (expires && Number.isNaN(new Date(expires).getTime())) die("expires must be a date like 2027-12-31")
  if (!existsSync(privatePath)) die(`No private key at ${privatePath}. Run: node tools/license.mjs init`)
  const payload = {
    v: 1,
    id: "LIC-" + randomBytes(4).toString("hex").toUpperCase(),
    client,
    profile,
    machineId: machine.toUpperCase(),
    issuedAt: new Date().toISOString(),
    expiresAt: expires ? new Date(expires + "T23:59:59Z").toISOString() : null,
  }
  const json = JSON.stringify(payload)
  const sig = sign(null, Buffer.from(json), createPrivateKey(readFileSync(privatePath)))
  const key = `ERP1.${b64u(json)}.${b64u(sig)}`
  appendFileSync(join(dir, "issued.log"), JSON.stringify(payload) + "\n")
  console.log(key)
} else if (cmd === "inspect") {
  const key = (args[0] || "").replace(/\s+/g, "")
  const parts = key.split(".")
  if (parts.length !== 3 || parts[0] !== "ERP1") die("Not a license key")
  const json = Buffer.from(parts[1], "base64url")
  const ok = verify(null, json, createPublicKey(readPublicFromSource()), Buffer.from(parts[2], "base64url"))
  console.log(JSON.stringify({ signatureValid: ok, payload: JSON.parse(json.toString()) }, null, 2))
} else {
  console.log("Commands: init | issue --client --profile --machine [--expires] | inspect <key>")
  void createHash
}
